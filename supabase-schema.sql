-- Run this in the Supabase SQL Editor.
create table if not exists public.devotionals (
  id bigint generated by default as identity primary key,
  title text not null,
  scripture text not null,
  date date not null,
  body text not null,
  reflection text not null,
  takeaway text not null,
  prayer text not null,
  status text not null default 'draft' check (status in ('draft','scheduled','published')),
  publish_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.devotionals enable row level security;
-- Anyone can read only published devotionals whose publication time has arrived.
create policy "Public can read published devotionals"
on public.devotionals for select to anon, authenticated
using (status in ('published','scheduled') and publish_at <= now());
-- Authenticated administrators can manage content. Create admin users only
-- from Supabase Authentication; do not enable public sign-up.
create policy "Authenticated admins can manage devotionals"
on public.devotionals for all to authenticated
using (auth.uid() is not null)
with check (auth.uid() is not null);
